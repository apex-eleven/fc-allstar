/**
 * ค่าตั้งของระบบผสมการ์ด (config/fusion) — แอดมินปรับได้ทั้งหมดจากหน้า ADMIN → ผสมการ์ด
 *
 * เก็บเป็นโครงแบน ๆ ชั้นเดียวโดยตั้งใจ เพราะ Firestore merge ทีละฟิลด์ได้ง่ายกว่า
 * และหน้าแอดมินผูกช่องกรอกกับฟิลด์ได้ตรง ๆ ไม่ต้องไล่ path ซ้อน
 *
 * ⚠️ odds เป็น map ของ "ค่าบวกต่ำสุดของวัสดุ" → น้ำหนักของผลลัพธ์ +1 ถึง +8
 * เป็น map-of-array ไม่ใช่ array-of-array เพราะ Firestore เก็บ array ซ้อน array ไม่ได้
 */

/** จำนวนช่องในหนึ่งแถวของตารางโอกาส = ผลลัพธ์ +1 ถึง +8 */
export interface FusionConfig {
  /** false = ปิดระบบ ซ่อนเมนู Fusion จากผู้เล่นทุกคน */
  enabled: boolean;
  /** ใช้การ์ดกี่ใบต่อการผสมหนึ่งครั้ง */
  materials: number;
  /** โชว์การ์ดคว่ำให้เลือกเปิดกี่ใบ */
  candidates: number;
  /**
   * ตารางน้ำหนักการสุ่ม — คีย์คือค่าบวกต่ำสุดของวัสดุ ('0' ถึง '8')
   * แต่ละแถวมี 8 ตัวเลข = น้ำหนักของผลลัพธ์ +1, +2, … , +8
   *
   * ไม่จำเป็นต้องรวมกันได้ 100 — ระบบคิดเป็นสัดส่วนให้เอง
   * (แถวที่ใส่ 10/10/10 มีค่าเท่ากับ 1/1/1 ทุกประการ)
   */
  odds: Record<string, number[]>;
  /** false = ปิดโบนัสเงิน ไม่ว่าวัสดุจะบวกสูงแค่ไหน */
  cashEnabled: boolean;
  /** ต้องใช้การ์ด +N ขึ้นไป "ครบทุกใบ" ถึงจะมีสิทธิ์ลุ้นเงิน */
  cashMinPlus: number;
  /** โอกาสได้เงินเมื่อเข้าเงื่อนไขแล้ว (0–1) */
  cashChance: number;
  /** เงินก้อนต่ำสุด/สูงสุดที่แถมได้ */
  cashMin: number;
  cashMax: number;
  /** ปัดเงินเป็นขั้นละเท่าไร */
  cashStep: number;
}
