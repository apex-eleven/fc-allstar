/**
 * ระบบล็อกการ์ด (config/cardLock) — ADMIN → ล็อกการ์ด
 *
 * ล็อกไว้ = การ์ดใบนั้น "หาไม่ได้" จากทุกระบบในเกม (ซอง ผสม ตลาด ร้านแลก กล่องสุ่ม พาส ฯลฯ)
 * แต่ผู้เล่นที่มีอยู่แล้ว ยังใช้ ตีบวก จัดทีม ขาย และผสมทิ้งได้ตามปกติทุกอย่าง
 *
 * ใช้กับ "นักเตะต้นแบบ" (playerId) ไม่ใช่การ์ดรายใบของผู้เล่น
 * เพราะจุดประสงค์คือกันไม่ให้ของหลุดเข้าเกมก่อนเวลา ไม่ใช่ยึดของที่แจกไปแล้ว
 */
export interface CardLockConfig {
  /** playerId ที่ถูกล็อกอยู่ตอนนี้ */
  ids: string[];
  /** ข้อความที่โชว์ให้ผู้เล่นเห็นตรงของที่ถูกล็อก (ว่าง = ใช้ข้อความเริ่มต้น) */
  note: string;
}
